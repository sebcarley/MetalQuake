/*
QuakeM5 -- the Metal Shading Language shader (METAL.md Phase 3, slice 4).

Included as a C string array, exactly like shader_glsl.h:
    static const char *builtinmslstrings[] = { #include "shader_msl.h" 0 };
and compiled at runtime through newLibraryWithSource:, because the offline
Metal toolchain is not installed on this machine (verified: `xcrun metal`
reports a missing Metal Toolchain component).

DRIVEN BY THE SAME PRETEXT AS THE GLSL. R_GLSL_CompilePermutation builds the
"#define MODE_x / #define USEy / static parms / DPD_SHADER_PRELUDE" list once,
from the same shadermodeinfo and shaderpermutationinfo tables, and hands it to
both compilers. So the two languages cannot select different features even in
principle -- only the bodies below can differ, and only where they are written
to.

SCOPE, and why this is not the uber-shader. Ported, each narrowed on
measurement at its phase: MODE_VERTEXCOLOR (+ALPHAGENVERTEX) and MODE_GENERIC
(Phase 3, the 2D path, the blits, particles and explosions); MODE_LIGHTMAP,
MODE_DEPTH_OR_SHADOW and minimal MODE_POSTPROCESS (Phase 4a, the opaque
world); MODE_LIGHTDIRECTION (Phase 4b, entities -- and the SKY SPHERE, which
rides this mode via R_DrawCustomSurface, not VERTEXCOLOR as the 4a record
first said) for perm 0, GLOW, ALPHAKILL, ALPHAGENVERTEX, COLORMAPPING,
DIFFUSE; MODE_LIGHTSOURCE (Phase 4c, rtlight additive passes) and classic
fog for the whole shared arm (4c-3, FOGINSIDE/FOGOUTSIDE/FOGALPHAHACK).
Everything else -- WATER/REFRACTION, the deferred modes, the murk -- compiles
to the MAGENTA SENTINEL, which remains the standing acceptance requirement:
an unported arm must be unmistakable on screen rather than looking like
geometry that failed to draw.

ON THE DUPLICATION, HONESTLY. METAL.md says the shader-body split must land
before any MSL exists, and calls it non-negotiable. Its stated reason is the
murk density model becoming a three-way lockstep -- and none of the density
model is here; it lives in MODE_VOLUMETRICFOG, which is Phase 6. What IS
duplicated from shader_glsl.h is a few dozen lines of arithmetic, each
marked LOCKSTEP below with the shader_glsl.h construct it mirrors. They are
covered by pixel gates (the 2D max-delta-2 bed, and the 4a/4b/4c world-gate
vantages) that the density model has never had. Agreed with Seb 2026-08-05;
METAL.md's rule is scoped to the surface/fog shader rather than overridden.

TEXTURE INDICES ARE A LOCKSTEP RULE, and an easy one to get silently wrong.
gl_rmain.c's sampler block (search "bind the texture samplers in use") walks a
FIXED list -- First, Second, GammaRamps, Normal, Color, Gloss, ... -- and assigns
unit numbers sequentially over whichever of them the compiled shader actually
declares. So the rule here is: declare textures in THAT order, numbered 0..n over
exactly the ones declared. Get it wrong and textures bind to the wrong slots --
the shader samples an index nothing was bound to, which returns zero rather than
erroring.

It used to leave nothing in any log, and it cost MODE_GENERIC a real defect (see
that arm). Since Phase 4d, Metal_Backend_SetUniformInt ASSERTS the rule: it is
the one place where the index the MSL declared and the unit the walk assigned
meet, so a single check there covers all 37 textures in every mode and every
permutation the engine compiles. Prefer a COMPUTED index (the DP_TEX_* macros)
over a literal wherever a permutation bit can add or remove a slot before it.

USELAVA and USEREDGLOW are static parms that are ON by default (r_lavaboil 0.6,
r_redglow 1.5), so GL's compiled surface program textually contains both blocks
and both get real uniform locations. Both are arithmetic no-ops where they do not
apply -- RedGlow.x is zeroed for ui batches, and LavaParams is zeroed for
anything without SUPERCONTENTS_LAVA, which its own comment calls "an exact
no-op". BOTH ARE IMPLEMENTED HERE AS OF 6-4, so both locations come back >= 0 on
either backend. (This paragraph used to say both were omitted and that
loc_RedGlow came back -1 on Metal; USEREDGLOW was implemented in Phase 4 and the
note was never updated, so it had been wrong about half its own subject for two
phases. USELAVA was the true half, until 6-4.)
*/

